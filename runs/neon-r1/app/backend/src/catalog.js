export function roundMoney(n) {
  return Math.round((Number(n) + Number.EPSILON) * 100) / 100;
}

export function calculateChaosPricing({
  items = [],
  shippingMethod = "snail_helmet",
  promoCode = "",
  addons = [],
}) {
  const normalizedItems = [];
  let subtotal = 0;

  for (const rawItem of items) {
    const product = PRODUCTS.find((p) => p.id === rawItem.productId);
    if (!product) continue;
    const qty = Math.max(1, Math.min(99, Number(rawItem.quantity) || 1));
    const lineTotal = roundMoney(product.price * qty);
    subtotal = roundMoney(subtotal + lineTotal);
    normalizedItems.push({
      productId: product.id,
      sku: product.sku,
      name: product.name,
      unitPrice: product.price,
      quantity: qty,
      lineTotal,
    });
  }

  // Fallback item if cart somehow arrived empty so checkout still completes cleanly
  if (normalizedItems.length === 0) {
    const fallback = PRODUCTS[0];
    subtotal = fallback.price;
    normalizedItems.push({
      productId: fallback.id,
      sku: fallback.sku,
      name: fallback.name,
      unitPrice: fallback.price,
      quantity: 1,
      lineTotal: fallback.price,
    });
  }

  const shipping =
    SHIPPING_METHODS.find((m) => m.id === shippingMethod) || SHIPPING_METHODS[0];

  const selectedAddons = CHECKOUT_ADDONS.filter((a) =>
    Array.isArray(addons) ? addons.includes(a.id) : false
  );
  const addonsTotal = roundMoney(
    selectedAddons.reduce((sum, a) => sum + a.price, 0)
  );

  // Mandatory ridiculous fees
  const fees = [
    {
      name: "Convenience Inconvenience Fee",
      amount: 49.99,
    },
    {
      name: "Digital Oxygen & Pixel Tax",
      amount: 12.34,
    },
    {
      name: "CEO's Yacht Fuel Surcharge",
      amount: roundMoney(Math.max(45, subtotal * 0.02)),
    },
    {
      name: "Gravity Calibration Fee",
      amount: 19.95,
    },
  ];

  const normalizedPromo = String(promoCode || "").trim().toUpperCase();
  let promoPenalty = 0;
  let promoMessage = "No promo code entered (we appreciate your surrender).";

  if (normalizedPromo) {
    if (PROMO_CODES[normalizedPromo]) {
      promoPenalty = PROMO_CODES[normalizedPromo].penalty;
      promoMessage = PROMO_CODES[normalizedPromo].message;
    } else {
      promoPenalty = 17.5;
      promoMessage = `Unknown promo '${normalizedPromo}' detected! Added $17.50 Guessing Penalty!`;
    }
    fees.push({
      name: `Reverse Promo Surcharge (${normalizedPromo})`,
      amount: promoPenalty,
    });
  }

  const feesTotal = roundMoney(fees.reduce((sum, f) => sum + f.amount, 0));
  const grandTotal = roundMoney(
    subtotal + shipping.price + addonsTotal + feesTotal
  );

  return {
    items: normalizedItems,
    subtotal,
    shippingMethod: shipping.id,
    shippingLabel: shipping.label,
    shippingEta: shipping.eta,
    shippingCost: shipping.price,
    addons: selectedAddons,
    addonsTotal,
    fees,
    feesTotal,
    promoCode: normalizedPromo,
    promoPenalty,
    promoMessage,
    grandTotal,
    currency: "USD",
  };
}
